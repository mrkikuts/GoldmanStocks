const languageMap: Record<AppLanguage, AppLocale> = { ET: 'et', EN: 'en', LV: 'lv' };
const localeMap: Record<AppLocale, string> = { et: 'et-EE', en: 'en-GB', lv: 'lv-LV' };

const deviceLanguage = getLocales()[0]?.languageCode;
const initialLanguage: AppLocale =
  deviceLanguage === 'et' || deviceLanguage === 'lv' ? deviceLanguage : 'en';

const i18n = createInstance();

void i18n.use(initReactI18next).init({
  resources: { en: { translation: en }, et: { translation: et }, lv: { translation: lv } },
  lng: initialLanguage,
  fallbackLng: 'en',
  supportedLngs: ['en', 'et', 'lv'],
  interpolation: { escapeValue: false },
  compatibilityJSON: 'v4',
});

export function languageCodeToLocale(language: AppLanguage): AppLocale {
  return languageMap[language];
}

export function getIntlLocale(): string {
  const language = i18n.resolvedLanguage;
  return localeMap[language === 'et' || language === 'en' || language === 'lv' ? language : 'en'];
}

export async function setAppLanguage(language: AppLanguage): Promise<void> {
  await i18n.changeLanguage(languageCodeToLocale(language));
  await AsyncStorage.setItem(LANGUAGE_KEY, language);
}

export async function restoreStoredLanguage(): Promise<void> {
  const language = await AsyncStorage.getItem(LANGUAGE_KEY);
  if (language === 'ET' || language === 'EN' || language === 'LV') await setAppLanguage(language);
}

